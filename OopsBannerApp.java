public class Main {
    public static void main(String[] args) {

        // Using String.join to join parts with space
        System.out.println(String.join(" ", "   ***   ", " ***** "));
        System.out.println(String.join(" ", " **   ** ", " **     "));
        System.out.println(String.join(" ", " **   ** ", " **     "));
        System.out.println(String.join(" ", " **   ** ", " *****  "));
        System.out.println(String.join(" ", " **   ** ", "     ** "));
        System.out.println(String.join(" ", " **   ** ", "     ** "));
        System.out.println(String.join(" ", "   ***   ", " *****  "));
    }
}
